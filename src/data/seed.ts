function custody(events: Array<[string, string, string]>, currentIndex: number, upcoming: string[]): CustodyEvent[] {
  const done: CustodyEvent[] = events.map(([label, timestamp, method], i) => ({
    id: `ce-${label}-${i}`,
    label,
    timestamp,
    method,
    status: i === currentIndex ? "current" : "done",
  }));
  const rest: CustodyEvent[] = upcoming.map((label, i) => ({
    id: `ce-up-${label}-${i}`,
    label,
    timestamp: "",
    method: "Pending",
    status: "upcoming",
  }));
  return [...done, ...rest];
}

